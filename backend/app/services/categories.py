def _norm(text: str) -> str:
    return str(text or "").strip().lower()


def match_category(*texts: str) -> str:
    """把若干段文本（商户名 / 商品说明 / 备注 / 用户原话）拼起来判分类。

    返回一级分类名；判不出返回 `UNCONFIRMED_CATEGORY`（待确认），不瞎猜。
    传入多段文本是刻意的：备注里写了"早餐加午餐"，就能把便利店消费拉到餐饮。
    """
    blob = " ".join(_norm(t) for t in texts if t)
    if not blob:
        return UNCONFIRMED_CATEGORY

    # 一级分类名直接命中：识别结果回填的分类名（如"交通"）、用户直接说「餐饮」都走这条。
    # 必须放在最前，否则「交通」这种一级分类名反而匹配不到自己。
    for cat in CATEGORIES:
        if cat in blob:
            return cat

    # 一级：报销科目名（用户直接说"交通报销"）
    for alias, cat in REPORT_ALIASES.items():
        if alias.lower() in blob:
            return cat

    # 二级：关键词下沉（顺序敏感）
    for cat, words in KEYWORD_RULES:
        for w in words:
            if w in blob:
                return cat

    # 三级：口语别名
    for cat, words in SPOKEN_ALIASES.items():
        for w in words:
            if w in blob:
                return cat

    return UNCONFIRMED_CATEGORY


def match_platform(raw_category: str) -> str | None:
    """平台分类值 → 一级分类。返回 None 表示该值不含类别信息（需下沉到关键词）。"""
    return PLATFORM_MAP.get(str(raw_category or "").strip())


def match_income_category(*texts: str) -> str:
    """收入侧分类。判不出落「其他收入」。"""
    blob = " ".join(_norm(t) for t in texts if t)
    for cat, words in INCOME_KEYWORD_RULES:
        for w in words:
            if w.lower() in blob:
                return cat
    return "其他收入"


def normalize_category(raw: str, *context: str) -> str:
    """任意分类值归一化到一级分类。

    命中一级分类名直接用；否则用平台映射；再不行用 `context` 做关键词兜底；
    最后落「待确认」（若是"不计收支"类值则原样返回）。
    """
    s = str(raw or "").strip()
    if s in NEUTRAL_VALUES:
        return NEUTRAL_CATEGORY
    if s in CATEGORIES:
        return s
    mapped = match_platform(s)
    if mapped:
        return mapped
    # 平台值是明确的中性项（投资理财/信用借还/保险）
    if s in PLATFORM_MAP and PLATFORM_MAP[s] is None:
        return UNCONFIRMED_CATEGORY
    # 没有额外上下文时，用原值本身做关键词兜底：
    # 这样账本里的旧分类名（如「设计」「接单」「房租」）也能落到新分类上
    return match_category(*context) if context else match_category(s)


def is_rigid(*texts: str) -> bool:
    """是否刚性支出（不可压缩 / 有法定义务 / 按月固定）。"""
    blob = " ".join(_norm(t) for t in texts if t)
    return any(w in blob for w in RIGID_WORDS)


def is_business(*texts: str) -> bool:
    """是否疑似经营成本（措辞红线：只说"疑似经营成本"，不判能不能抵税）。"""
    blob = " ".join(_norm(t) for t in texts if t)
    return any(w in blob for w in BUSINESS_WORDS)


